//! Procedural sources, generated entities, overrides and regeneration (ADR-0017).
//!
//! An authored *source* entity carries [`Procedural`] `{ generator, seed }`
//! plus its generator's parameter component (for a ProcGraph, [`GraphSource`]).
//! Its output is a set of *generated* entities under it, each with a
//! generator-chosen key and the id `<source id>/<key>`. The scene file stores
//! only the source: generator, seed, parameters and the [`Overrides`] of
//! generated entities. Generated entities are never saved.
//!
//! Generators return plain data (a [`SceneFragment`] of [`GenNode`]s naming
//! components and fields by string), so a generator written in Luau produces
//! exactly what one written in Rust does.
//!
//! **Regeneration** ([`World::regenerate_changed`](crate::World::regenerate_changed))
//! runs a source's generator when the fingerprint of its inputs changed
//! (generator name, seed, parameter values and the generator's
//! `fingerprint_extra`), and applies the new fragment as a diff:
//! * an entity whose key survives keeps its `Entity` and is updated in place;
//! * new keys are spawned, vanished keys are despawned;
//! * `MeshRef` / `MaterialRef` assets no longer referenced anywhere are listed
//!   in [`RegenReport::released_assets`];
//! * overrides are re-applied by key; a key with a deletion override or a
//!   [suppression](crate::World::suppress) is not spawned (nor are its
//!   generated descendants);
//! * overrides whose key is no longer generated are kept and reported as
//!   [`Orphan`]s;
//! * a failing generator leaves the previous output in place.

