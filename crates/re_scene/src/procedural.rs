/// A generator's output (and what a prefab instantiates into).
pub type SceneFragment = Vec<GenNode>;

/// What a generator sees: read access to the world, the source, its seed and
/// its parameters.
pub struct GenContext<'a> {
    world: &'a World,
    source: Entity,
    source_id: &'a str,
    seed: i64,
    version: i64,
    params_component: &'a str,
}

impl<'a> GenContext<'a> {
    /// The world (read only).
    pub fn world(&self) -> &'a World {
        self.world
    }

    /// The source entity.
    pub fn source(&self) -> Entity {
        self.source
    }

    /// The source's stable id.
    pub fn source_id(&self) -> &'a str {
        self.source_id
    }

    /// The source's `Procedural.seed`.
    pub fn seed(&self) -> i64 {
        self.seed
    }

    /// The generator version the source records (`Procedural.version`).
    pub fn version(&self) -> i64 {
        self.version
    }

    /// Reads a field of the generator's parameter component on the source.
    pub fn param<T: FieldValue>(&self, field: &str) -> Result<T, Diagnostic> {
        let v = self.param_value(field)?;
        T::from_value(&v).ok_or_else(|| {
            self.error(format!(
                "{}.{field} has an unexpected type",
                self.params_component
            ))
        })
    }

    /// Reads a field of the parameter component as a [`Value`].
    pub fn param_value(&self, field: &str) -> Result<Value, Diagnostic> {
        self.world
            .get(self.source_id, self.params_component, field)
            .map_err(|e| e.to_diagnostic())
    }

    /// A deterministic random number in `[0, 1)` for `key`: the same key and
    /// seed always give the same number, whatever else changed.
    pub fn random(&self, key: &str) -> f32 {
        (self.random_u64(key) >> 40) as f32 / (1u64 << 24) as f32
    }

    /// A deterministic random 64-bit value for `key` (see [`GenContext::random`]).
    pub fn random_u64(&self, key: &str) -> u64 {
        let h = blake3::hash(key.as_bytes());
        let mut bytes = [0u8; 8];
        bytes.copy_from_slice(&h.as_bytes()[..8]);
        let mut state = (self.seed as u64) ^ u64::from_le_bytes(bytes);
        splitmix64(&mut state)
    }

    /// Read access to an ECS resource (for example a graph store), if present.
    pub fn resource<R: Resource>(&self) -> Option<&'a R> {
        self.world.ecs.get_resource::<R>()
    }

    /// A generator-failure diagnostic (`RE1207`) located at the source, for
    /// generators that have no codes of their own.
    pub fn error(&self, message: impl Into<String>) -> Diagnostic {
        Diagnostic::error(codes::GENERATOR_FAILED, message)
            .at(Location::entity(self.source_id.to_string()))
    }
}

/// A generator: reads its context and returns the fragment it wants to exist.
pub type GeneratorFn = Arc<dyn Fn(&GenContext) -> Result<SceneFragment, Diagnostic> + Send + Sync>;

/// Folds external input (such as a graph document) into a source's fingerprint.
pub type FingerprintFn = fn(&GenContext) -> u64;

/// A registered generator.
pub struct GeneratorInfo {
    /// The name a source's `Procedural.generator` uses.
    pub name: String,
    /// Documentation, shown by `describe`.
    pub doc: String,
    /// The component on the source holding this generator's parameters.
    pub params_component: String,
    /// The generator itself.
    pub run: GeneratorFn,
    /// Extra fingerprint input, for generators that read something besides
    /// the source's components.
    pub fingerprint_extra: Option<FingerprintFn>,
    /// The generator's current version (ADR-0043); new sources record it.
    pub version: u32,
    /// The oldest `Procedural.version` the generator still runs.
    pub oldest: u32,
}

impl fmt::Debug for GeneratorInfo {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("GeneratorInfo")
            .field("name", &self.name)
            .field("params_component", &self.params_component)
            .finish_non_exhaustive()
    }
}

/// The generator registry. Cheap to clone (generators are shared).
#[derive(Clone, Default, Debug)]
pub struct Generators {
    map: IndexMap<String, Arc<GeneratorInfo>>,
}

impl Generators {
    /// Registers (or replaces) a generator.
    pub fn register(&mut self, info: GeneratorInfo) {
        self.map.insert(info.name.clone(), Arc::new(info));
    }
    /// The generator named `name`.
    pub fn get(&self, name: &str) -> Option<&GeneratorInfo> {
        self.map.get(name).map(|a| &**a)
    }
    /// Every generator, in registration order.
    pub fn iter(&self) -> impl Iterator<Item = &GeneratorInfo> {
        self.map.values().map(|a| &**a)
    }
    /// The number of generators.
    pub fn len(&self) -> usize {
        self.map.len()
    }
    /// True if none is registered.
    pub fn is_empty(&self) -> bool {
        self.map.is_empty()
    }
    fn shared(&self, name: &str) -> Option<Arc<GeneratorInfo>> {
        self.map.get(name).cloned()
    }
}

/// An override whose target key is no longer generated. It stays in the
/// source's override list (and in the file).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Orphan {
    /// The source's id.
    pub source: String,
    /// The target key.
    pub target: String,
    /// The component of a field override (`None` for a deletion override).
    pub component: Option<String>,
    /// The field of a field override (`None` for a deletion override).
    pub field: Option<String>,
}

impl fmt::Display for Orphan {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match (&self.component, &self.field) {
            (Some(c), Some(field)) => write!(
                f,
                "{}: override of {c}.{field} on {:?} has no target in the new output; kept",
                self.source, self.target
            ),
            _ => write!(
                f,
                "{}: deletion override on {:?} has no target in the new output; kept",
                self.source, self.target
            ),
        }
    }
}

/// What a regeneration did.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct RegenReport {
    /// Ids of the sources whose generator ran (successfully or not).
    pub sources: Vec<String>,
    /// Ids of newly spawned generated entities.
    pub spawned: Vec<String>,
    /// Ids of generated entities whose key survived (same `Entity`, updated in place).
    pub updated: Vec<String>,
    /// Ids of generated entities despawned because their key vanished (or is
    /// now deleted or suppressed).
    pub despawned: Vec<String>,
    /// Overrides whose target key is no longer generated (kept).
    pub orphans: Vec<Orphan>,
    /// `MeshRef` / `MaterialRef` assets that were referenced by the old output
    /// and are no longer referenced by any entity, sorted.
    pub released_assets: Vec<String>,
    /// Generator failures (`RE1207`, error) and overrides that could not be
    /// applied (`RE1209`, warning).
    pub diagnostics: Vec<Diagnostic>,
}

impl RegenReport {
    /// True if no generator ran.
    pub fn is_empty(&self) -> bool {
        self.sources.is_empty()
    }

    /// The orphan messages followed by the diagnostics' messages (the core
    /// spike's warning strings).
    pub fn warnings(&self) -> Vec<String> {
        self.orphans
            .iter()
            .map(ToString::to_string)
            .chain(self.diagnostics.iter().map(|d| d.message.clone()))
            .collect()
    }

    /// Appends another report.
    pub fn merge(&mut self, other: RegenReport) {
        self.sources.extend(other.sources);
        self.spawned.extend(other.spawned);
        self.updated.extend(other.updated);
        self.despawned.extend(other.despawned);
        self.orphans.extend(other.orphans);
        self.released_assets.extend(other.released_assets);
        self.released_assets.sort();
        self.released_assets.dedup();
        self.diagnostics.extend(other.diagnostics);
    }
}

/// The fingerprint of `source`'s generator inputs, or `None` if it is not a
/// procedural source.
pub(crate) fn fingerprint(world: &World, source: Entity) -> Option<u64> {
    let mut h = DefaultHasher::new();
    let p = world.ecs.get::<Procedural>(source)?;
    p.generator.hash(&mut h);
    p.seed.hash(&mut h);
    p.version.hash(&mut h);
    if let Some(info) = world.generators.get(&p.generator) {
        if let Some(key) = world.registry.try_key(&info.params_component) {
            format!("{:?}", world.registry.get_all(&world.ecs, source, key)).hash(&mut h);
        }
        if let Some(extra) = info.fingerprint_extra
            && let Some(id) = world.id_of(source)
        {
            let ctx = GenContext {
                world,
                source,
                source_id: id,
                seed: p.seed,
                version: p.version,
                params_component: &info.params_component,
            };
            extra(&ctx).hash(&mut h);
        }
    }
    Some(h.finish())
}

