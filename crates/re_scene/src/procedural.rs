fn generator_failed(source_id: &str, message: String, cause: Option<Diagnostic>) -> SceneError {
    SceneError::GeneratorFailed {
        source_id: source_id.to_string(),
        message,
        cause: cause.map(Box::new),
    }
}

/// Runs `source`'s generator and applies its output as a diff. On error the
/// previous output is left in place.
pub(crate) fn regenerate(world: &mut World, source: Entity) -> Result<RegenReport, SceneError> {
    let src_id = world
        .id_of(source)
        .ok_or_else(|| SceneError::Invalid("procedural source needs a stable id".into()))?
        .to_string();
    let p = world
        .ecs
        .get::<Procedural>(source)
        .cloned()
        .ok_or_else(|| {
            SceneError::from(re_reflect::ReflectError::MissingComponent {
                component: "Procedural".into(),
            })
        })?;
    let info = world.generators.shared(&p.generator).ok_or_else(|| {
        generator_failed(
            &src_id,
            format!("unknown generator {:?}", p.generator),
            None,
        )
    })?;

    if p.version < i64::from(info.oldest.max(1)) || p.version > i64::from(info.version) {
        return Err(generator_failed(
            &src_id,
            format!(
                "generator {} cannot run version {} (it runs {} to {})",
                p.generator,
                p.version,
                info.oldest.max(1),
                info.version
            ),
            None,
        ));
    }

    // Run first, so a failing generator leaves the previous output in place.
    let nodes = {
        let ctx = GenContext {
            world,
            source,
            source_id: &src_id,
            seed: p.seed,
            version: p.version,
            params_component: &info.params_component,
        };
        (info.run)(&ctx).map_err(|d| {
            generator_failed(
                &src_id,
                format!("generator {}: {}", p.generator, d.message),
                Some(d),
            )
        })?
    };

    apply_output(world, source, &src_id, &p.generator, Scope::Whole, &nodes)
}

/// Which part of a source's output a fragment replaces.
#[derive(Clone, Copy)]
pub(crate) enum Scope<'a> {
    /// Everything the source generated, except its loaded stream cells.
    Whole,
    /// The content of one loaded stream cell: the generated entities under
    /// the cell's root entity, whose keys all start with `<key>/`.
    Cell {
        /// The cell's root entity (generated by the source, `LoadedCell`).
        root: Entity,
        /// The cell's key (`c/<x>_<z>`).
        key: &'a str,
    },
}

impl Scope<'_> {
    /// True if an override target belongs to this scope.
    fn owns_target(&self, streamed: bool, target: &str) -> bool {
        match self {
            Scope::Whole => !(streamed && crate::stream::owning_cell(target).is_some()),
            Scope::Cell { key, .. } => crate::stream::owning_cell(target) == Some(*key),
        }
    }
}

/// The generated entities of `source` in `scope`, by key.
fn current_output(world: &World, source: Entity, scope: Scope) -> HashMap<String, Entity> {
    let root = match scope {
        Scope::Whole => source,
        Scope::Cell { root, .. } => root,
    };
    let mut existing = HashMap::new();
    let mut stack = vec![root];
    while let Some(e) = stack.pop() {
        if e != root {
            if world.ecs.get::<crate::stream::LoadedCell>(e).is_some() {
                continue;
            }
            if let Some(g) = world.ecs.get::<Generated>(e)
                && g.source == source
            {
                existing.insert(g.key.clone(), e);
            }
        }
        stack.extend(children(&world.ecs, e).iter().copied());
    }
    existing
}

/// Applies a generator's output (`nodes`) to the part of `source`'s output
/// that `scope` names, as the diff described in the module docs.
pub(crate) fn apply_output(
    world: &mut World,
    source: Entity,
    src_id: &str,
    generator: &str,
    scope: Scope,
    nodes: &[GenNode],
) -> Result<RegenReport, SceneError> {
    let src_id = src_id.to_string();
    let root = match scope {
        Scope::Whole => source,
        Scope::Cell { root, .. } => root,
    };
    let streamed = world.ecs.get::<crate::stream::Streamed>(source).is_some();
    // The current output, by key.
    let mut existing = current_output(world, source, scope);

    // Validate and resolve everything before changing anything.
    let mut prepared = Vec::with_capacity(nodes.len());
    let mut seen: HashSet<&str> = HashSet::new();
    for node in nodes {
        if node.key.is_empty() {
            return Err(generator_failed(
                &src_id,
                format!("generator {generator} produced an empty key"),
                None,
            ));
        }
        match scope {
            Scope::Cell { key, .. } if !crate::stream::under(&node.key, key) => {
                return Err(generator_failed(
                    &src_id,
                    format!("node {:?} is not under cell {key:?}", node.key),
                    None,
                ));
            }
            Scope::Whole if streamed && crate::stream::in_cell(&node.key).is_some() => {
                return Err(generator_failed(
                    &src_id,
                    format!(
                        "node {:?}: keys under a cell (`c/<x>_<z>/…`) are applied per cell on a streamed source",
                        node.key
                    ),
                    None,
                ));
            }
            _ => {}
        }
        // The id must be free, or be this key's own current entity, so the
        // id index stays one-to-one.
        let id = format!("{src_id}/{}", node.key);
        if let Some(holder) = world.ids().get(&id)
            && existing.get(&node.key) != Some(&holder)
        {
            return Err(generator_failed(
                &src_id,
                format!(
                    "node {:?}: id {id:?} is already taken by another entity",
                    node.key
                ),
                None,
            ));
        }
        if !seen.insert(node.key.as_str()) {
            return Err(generator_failed(
                &src_id,
                format!("generator {generator} produced key {:?} twice", node.key),
                None,
            ));
        }
        if let Some(k) = &node.parent_key
            && (!seen.contains(k.as_str()) || k == &node.key)
        {
            return Err(generator_failed(
                &src_id,
                format!(
                    "node {:?}: parent key {k:?} not generated before it",
                    node.key
                ),
                None,
            ));
        }
        let mut components = Vec::with_capacity(node.components.len());
        for (cname, fields) in &node.components {
            let resolved = (|| -> Result<(ComponentKey, Vec<Value>), SceneError> {
                let key = world.registry.key(cname)?;
                let schema = world.registry.schema(key);
                let mut values = schema.defaults();
                for (fname, v) in fields {
                    let i = schema.field_index(fname)?;
                    let f = &schema.fields[i];
                    values[i] = f.ty.coerce(v.clone()).map_err(|error| {
                        re_reflect::ReflectError::Value {
                            path: format!("{}.{}", schema.name, f.name),
                            error,
                        }
                    })?;
                }
                Ok((key, values))
            })();
            let (key, values) = resolved.map_err(|e| {
                generator_failed(
                    &src_id,
                    format!("node {:?}: {e}", node.key),
                    Some(e.to_diagnostic()),
                )
            })?;
            components.push((key, values));
        }
        prepared.push(PreparedNode {
            key: node.key.clone(),
            name: node.name.clone(),
            parent_key: node.parent_key.clone(),
            components,
        });
    }

    let mut report = RegenReport {
        sources: vec![src_id.clone()],
        ..Default::default()
    };
    let overrides = world
        .ecs
        .get::<Overrides>(source)
        .cloned()
        .unwrap_or_default();

    // Orphans: overrides whose target key is not in the output at all.
    let mut all_keys: HashSet<&str> = prepared.iter().map(|n| n.key.as_str()).collect();
    if let Scope::Cell { key, .. } = scope {
        // The cell root always exists; `World::apply_cell` applies its overrides.
        all_keys.insert(key);
    }
    for o in &overrides.0 {
        if scope.owns_target(streamed, o.target()) && !all_keys.contains(o.target()) {
            report.orphans.push(match o {
                OverrideDoc::Field {
                    target,
                    component,
                    field,
                    ..
                } => Orphan {
                    source: src_id.clone(),
                    target: target.clone(),
                    component: Some(component.clone()),
                    field: Some(field.clone()),
                },
                OverrideDoc::Deleted { target } => Orphan {
                    source: src_id.clone(),
                    target: target.clone(),
                    component: None,
                    field: None,
                },
            });
        }
    }

    // Skipped keys: deleted, suppressed, or under a skipped parent.
    let suppressions = world.ecs.get_resource::<Suppressions>().cloned();
    let mut skipped: HashSet<String> = HashSet::new();
    for n in &prepared {
        let id = format!("{src_id}/{}", n.key);
        let skip = overrides.is_deleted(&n.key)
            || suppressions.as_ref().is_some_and(|s| s.contains(&id))
            || n.parent_key.as_ref().is_some_and(|k| skipped.contains(k));
        if skip {
            skipped.insert(n.key.clone());
        }
    }

    // Apply field overrides to the prepared values.
    for o in &overrides.0 {
        let OverrideDoc::Field {
            target,
            component,
            field,
            value,
        } = o
        else {
            continue;
        };
        if skipped.contains(target) {
            continue;
        }
        let Some(node) = prepared.iter_mut().find(|n| &n.key == target) else {
            continue;
        };
        let applied = (|| -> Result<(), SceneError> {
            let key = world.registry.key(component)?;
            let schema = world.registry.schema(key);
            let index = schema.field_index(field)?;
            let ids = world.ids();
            let v = value
                .to_value(&schema.fields[index].ty, &|id| ids.get(id))
                .map_err(|error| re_reflect::ReflectError::Value {
                    path: format!("{component}.{field}"),
                    error,
                })?;
            let Some((_, values)) = node.components.iter_mut().find(|(k, _)| *k == key) else {
                return Err(re_reflect::ReflectError::MissingComponent {
                    component: component.clone(),
                }
                .into());
            };
            values[index] = v;
            Ok(())
        })();
        if let Err(e) = applied {
            report.diagnostics.push(
                Diagnostic::warning(
                    codes::OVERRIDE_NOT_APPLIED,
                    format!("{src_id}: override on {target:?} not applied: {e}"),
                )
                .at(Location::entity(src_id.clone()))
                .with_related(e.to_diagnostic()),
            );
        }
    }

    // The assets the current output references.
    let old_assets: BTreeSet<String> = existing
        .values()
        .flat_map(|&e| asset_refs(world, e))
        .collect();

    // Apply: update survivors in place, spawn new keys.
    let mut by_key: HashMap<String, Entity> = HashMap::new();
    let mut order: Vec<(Entity, Entity)> = Vec::new();
    for node in prepared.into_iter().filter(|n| !skipped.contains(&n.key)) {
        let parent = match &node.parent_key {
            None => root,
            Some(k) => by_key[k],
        };
        let id = format!("{src_id}/{}", node.key);
        let entity = if let Some(e) = existing.remove(&node.key) {
            if world.ecs.get::<Name>(e).map(|n| n.0.as_str()) != Some(node.name.as_str()) {
                world.ecs.entity_mut(e).insert(Name(node.name.clone()));
            }
            if hierarchy::parent(&world.ecs, e) != Some(parent) {
                hierarchy::add_child(&mut world.ecs, parent, e);
            }
            let wanted: HashSet<ComponentKey> = node.components.iter().map(|(k, _)| *k).collect();
            for k in world.registry.components_of(&world.ecs, e) {
                if !wanted.contains(&k) {
                    world.registry.remove(&mut world.ecs, e, k);
                }
            }
            for (k, values) in node.components {
                if world.registry.has(&world.ecs, e, k) {
                    for (i, v) in values.into_iter().enumerate() {
                        world.registry.set_field(&mut world.ecs, e, k, i, v)?;
                    }
                } else {
                    world.registry.insert(&mut world.ecs, e, k, values)?;
                }
            }
            report.updated.push(id);
            e
        } else {
            let e = world
                .ecs
                .spawn((
                    StableId(id.clone()),
                    Name(node.name.clone()),
                    Generated {
                        source,
                        key: node.key.clone(),
                    },
                ))
                .id();
            hierarchy::add_child(&mut world.ecs, parent, e);
            for (k, values) in node.components {
                world.registry.insert(&mut world.ecs, e, k, values)?;
            }
            report.spawned.push(id);
            e
        };
        order.push((parent, entity));
        by_key.insert(node.key, entity);
    }

    // Despawn vanished keys (their surviving descendants were moved above).
    let mut vanished: Vec<(String, Entity)> = existing.into_iter().collect();
    vanished.sort();
    // Every vanished key is reported; one already gone went with a vanished
    // ancestor.
    for (key, e) in vanished {
        report.despawned.push(format!("{src_id}/{key}"));
        hierarchy::despawn_recursive(&mut world.ecs, e);
    }

    // Sibling order follows the output order, as in a fresh generation.
    let mut by_parent: IndexMap<Entity, Vec<Entity>> = IndexMap::new();
    for (parent, e) in order {
        by_parent.entry(parent).or_default().push(e);
    }
    for (parent, generated) in by_parent {
        order_generated_children(world, parent, source, &generated);
    }

    // Assets the old output used that nothing references any more.
    if !old_assets.is_empty() {
        let mut live: HashSet<String> = HashSet::new();
        let mut q = world
            .ecs
            .query::<(Option<&MeshRef>, Option<&MaterialRef>)>();
        for (m, mat) in q.iter(&world.ecs) {
            if let Some(m) = m {
                live.insert(m.asset.clone());
            }
            if let Some(mat) = mat {
                live.insert(mat.asset.clone());
            }
        }
        report.released_assets = old_assets
            .into_iter()
            .filter(|a| !live.contains(a))
            .collect();
    }
    Ok(report)
}

/// Puts `parent`'s children in the order a fresh load and generation gives:
/// authored children first (in their order), then the children `source`
/// generated, in output order (`generated`), then `source`'s loaded stream
/// cells in key order, then children generated by other sources (in their
/// order). Does nothing when the order is already right.
pub(crate) fn order_generated_children(
    world: &mut World,
    parent: Entity,
    source: Entity,
    generated: &[Entity],
) {
    let current = children(&world.ecs, parent).to_vec();
    let source_of = |e: &Entity| world.ecs.get::<Generated>(*e).map(|g| g.source);
    let cell_of = |e: &Entity| {
        world
            .ecs
            .get::<crate::stream::LoadedCell>(*e)
            .map(|c| c.key.clone())
    };
    let mut desired: Vec<Entity> = current
        .iter()
        .filter(|e| source_of(e).is_none())
        .copied()
        .collect();
    desired.extend_from_slice(generated);
    let mut cells: Vec<(String, Entity)> = current
        .iter()
        .filter(|e| source_of(e) == Some(source))
        .filter_map(|e| cell_of(e).map(|k| (k, *e)))
        .collect();
    cells.sort();
    desired.extend(cells.into_iter().map(|(_, e)| e));
    desired.extend(
        current
            .iter()
            .filter(|e| source_of(e).is_some_and(|s| s != source)),
    );
    if desired == current || desired.len() != current.len() {
        return;
    }
    for (i, e) in desired.into_iter().enumerate() {
        hierarchy::insert_child(&mut world.ecs, parent, i, e);
    }
}

/// Despawns everything `source` generated and forgets its fingerprint: the
/// rule for a source that lost its `Procedural` (ADR-0043 §2, bake). Adding
/// `Procedural` back then regenerates the same output with the same ids.
pub(crate) fn clear_output(world: &mut World, source: Entity) -> RegenReport {
    let mut report = RegenReport::default();
    if let Some(id) = world.id_of(source) {
        report.sources.push(id.to_string());
    }
    let mut q = world.ecs.query::<(Entity, &Generated, &StableId)>();
    let mut generated: Vec<(String, Entity)> = q
        .iter(&world.ecs)
        .filter(|(_, g, _)| g.source == source)
        .map(|(e, _, id)| (id.0.clone(), e))
        .collect();
    generated.sort();
    let old_assets: BTreeSet<String> = generated
        .iter()
        .flat_map(|&(_, e)| asset_refs(world, e))
        .collect();
    for (id, e) in generated {
        report.despawned.push(id);
        hierarchy::despawn_recursive(&mut world.ecs, e);
    }
    if let Ok(mut e) = world.ecs.get_entity_mut(source) {
        e.remove::<GeneratedFingerprint>();
    }
    if !old_assets.is_empty() {
        let mut live: HashSet<String> = HashSet::new();
        let mut q = world
            .ecs
            .query::<(Option<&MeshRef>, Option<&MaterialRef>)>();
        for (m, mat) in q.iter(&world.ecs) {
            if let Some(m) = m {
                live.insert(m.asset.clone());
            }
            if let Some(mat) = mat {
                live.insert(mat.asset.clone());
            }
        }
        report.released_assets = old_assets
            .into_iter()
            .filter(|a| !live.contains(a))
            .collect();
    }
    report
}

fn asset_refs(world: &World, e: Entity) -> Vec<String> {
    let mut out = Vec::new();
    if let Some(m) = world.ecs.get::<MeshRef>(e)
        && !m.asset.is_empty()
    {
        out.push(m.asset.clone());
    }
    if let Some(m) = world.ecs.get::<MaterialRef>(e)
        && !m.asset.is_empty()
    {
        out.push(m.asset.clone());
    }
    out
}

/// The generated children of `source` (direct children only), in order.
pub fn generated_children(world: &World, source: Entity) -> Vec<Entity> {
    children(&world.ecs, source)
        .iter()
        .copied()
        .filter(|c| {
            world
                .ecs
                .get::<Generated>(*c)
                .is_some_and(|g| g.source == source)
        })
        .collect()
}
