//! `AGENTS.md`, `CLAUDE.md` and the MCP client configurations that
//! `real agent init` writes (ADR-0025).
//!
//! * `AGENTS.md`: [`generate_agents_md`], a fixed guide (the loop, `scene.apply`
//!   and the operation JSON, tiers) plus the command list from the registry;
//! * `CLAUDE.md`: `@AGENTS.md`, so Claude Code reads the same file;
//! * `.real/agent-policy.toml`: [`Policy::init_default`] (`edit` within the
//!   default scopes; committing it is the opt-in);
//! * client configs, each in its client's own format, all naming the server
//!   `real-engine`: `.mcp.json` (Claude Code, `mcpServers`),
//!   `.vscode/mcp.json` (VS Code, `servers` with `type`), `.cursor/mcp.json`
//!   (Cursor, `mcpServers`) and `.gemini/settings.json` (Gemini CLI,
//!   `mcpServers`). Codex and Zed keep their configuration outside the
//!   project, so [`init`] returns snippets for them instead.
//!
//! Existing files are respected: a JSON config gets the `real-engine` entry
//! merged in (other servers and keys stay), an existing policy is kept unless
//! `force` is set, and `AGENTS.md` / `CLAUDE.md` are only replaced when this
//! tool wrote them.

use std::path::Path;

use re_command::{CommandSpec, Tier};
use re_core::{Diagnostic, Location};
use serde_json::{Map, Value as Json, json};

use crate::codes;
use crate::policy::{Policy, policy_path};

/// The MCP server name in every client config (no underscore: Gemini CLI
/// builds rule names from it).
pub const SERVER_NAME: &str = "real-engine";

/// The first line of a generated `AGENTS.md`; a file without it is the
/// user's own and is never replaced.
pub const GENERATED_MARKER: &str =
    "<!-- Generated by `real agent init` from the command registry. Run it again to update. -->";

const GUIDE: &str = include_str!("../templates/AGENTS.md");

/// `real agent init`'s choices.
#[derive(Clone, Debug)]
pub struct InitOptions {
    /// The program clients start (`real`, or a path to it).
    pub program: String,
    /// Replace an existing `.real/agent-policy.toml`.
    pub force: bool,
}

impl Default for InitOptions {
    fn default() -> Self {
        InitOptions {
            program: "real".to_string(),
            force: false,
        }
    }
}

/// One client's configuration.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ClientConfig {
    /// The client's name (`Claude Code`, `VS Code`, ...).
    pub client: &'static str,
    /// The file, relative to the project root.
    pub path: &'static str,
    /// The top-level key that holds servers.
    pub key: &'static str,
    /// The `real-engine` entry.
    pub entry: Json,
}

/// What [`init`] did.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct InitReport {
    /// Files written (relative to the project root).
    pub written: Vec<String>,
    /// Files left alone, with the reason.
    pub kept: Vec<(String, String)>,
    /// Configuration for clients whose files live outside the project:
    /// `(client, where it goes, snippet)`.
    pub snippets: Vec<(String, String, String)>,
}

/// The `real-engine` entries of the project-local client configs.
