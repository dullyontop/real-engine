fn invalid(file: &str, msg: impl std::fmt::Display) -> CompatError {
    CompatError::InvalidData(format!("{file}: {msg}"))
}

fn check_header(file: &str, format: &str, version: u32, want: &str) -> Result<(), CompatError> {
    if format != want {
        return Err(invalid(
            file,
            format!("format is {format:?}, expected {want:?}"),
        ));
    }
    if version != DATA_VERSION {
        return Err(invalid(
            file,
            format!("version {version} is not supported (this build reads {DATA_VERSION})"),
        ));
    }
    Ok(())
}

fn parse<T: for<'de> Deserialize<'de>>(file: &str, text: &str) -> Result<T, CompatError> {
    serde_json::from_str(text).map_err(|e| invalid(file, e))
}

/// Checks that a `partial` row says what its gap is.
pub(crate) fn check_note(
    file: &str,
    what: &str,
    status: Status,
    note: &str,
) -> Result<(), CompatError> {
    if status == Status::Partial && note.trim().is_empty() {
        return Err(invalid(
            file,
            format!("{what} is partial but has no note saying what is missing"),
        ));
    }
    Ok(())
}

impl ClassFile {
    /// Parses and checks a class file; `file` names it in errors.
    pub fn parse(file: &str, text: &str) -> Result<ClassFile, CompatError> {
        let f: ClassFile = parse(file, text)?;
        check_header(file, &f.format, f.version, CLASS_FORMAT)?;
        Ok(f)
    }
}

impl EnumFile {
    /// Parses and checks an enum file: unique type and item names, unique
    /// item values, notes on partial rows.
    pub fn parse(file: &str, text: &str) -> Result<EnumFile, CompatError> {
        let f: EnumFile = parse(file, text)?;
        check_header(file, &f.format, f.version, ENUM_FORMAT)?;
        let mut names = BTreeSet::new();
        for e in &f.enums {
            if !names.insert(e.name.as_str()) {
                return Err(invalid(file, format!("enum {} is declared twice", e.name)));
            }
            if e.items.is_empty() {
                return Err(invalid(file, format!("enum {} has no items", e.name)));
            }
            check_note(file, &format!("Enum.{}", e.name), e.status, &e.note)?;
            let mut items = BTreeSet::new();
            let mut values = BTreeSet::new();
            for i in &e.items {
                if !items.insert(i.name.as_str()) {
                    return Err(invalid(
                        file,
                        format!("Enum.{}.{} is declared twice", e.name, i.name),
                    ));
                }
                if !values.insert(i.value) {
                    return Err(invalid(
                        file,
                        format!("Enum.{}.{} repeats the value {}", e.name, i.name, i.value),
                    ));
                }
            }
        }
        Ok(f)
    }
}

impl LibraryFile {
    /// Parses and checks a library file: unique member and record field
    /// names, member kinds that fit (`function`, `constant` or `property` on
    /// the table; `property` or `method` on values), notes on partial rows,
    /// and no members, value members or record on an instance global.
    pub fn parse(file: &str, text: &str) -> Result<LibraryFile, CompatError> {
        let f: LibraryFile = parse(file, text)?;
        check_header(file, &f.format, f.version, LIBRARY_FORMAT)?;
        for l in &f.libraries {
            check_note(file, &l.name, l.status, &l.note)?;
            if l.class.is_some()
                && !(l.members.is_empty() && l.value_members.is_empty() && l.record.is_empty())
            {
                return Err(invalid(
                    file,
                    format!(
                        "{} names a class, so its members come from the class",
                        l.name
                    ),
                ));
            }
            use LibraryMemberKind as K;
            let lists: [(&[LibraryMemberDoc], &[K], &str); 2] = [
                (
                    &l.members,
                    &[K::Function, K::Constant, K::Property],
                    "member",
                ),
                (&l.value_members, &[K::Property, K::Method], "value member"),
            ];
            for (list, allowed, what) in lists {
                let mut seen = BTreeSet::new();
                for m in list {
                    let path = format!("{}.{}", l.name, m.name);
                    if !seen.insert(m.name.as_str()) {
                        return Err(invalid(file, format!("{what} {path} is declared twice")));
                    }
                    if !allowed.contains(&m.kind) {
                        return Err(invalid(
                            file,
                            format!("{what} {path} cannot be a {}", m.kind.as_str()),
                        ));
                    }
                    check_note(file, &path, m.status, &m.note)?;
                }
            }
            let mut seen = BTreeSet::new();
            for f in &l.record {
                if !seen.insert(f.name.as_str()) {
                    return Err(invalid(
                        file,
                        format!("record {}.{} is declared twice", l.name, f.name),
                    ));
                }
            }
        }
        Ok(f)
    }
}

/// Every built-in data file, parsed: the classes, enums and libraries the
/// crate ships.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct DataSet {
    /// Class files, by file name.
    pub classes: Vec<(String, ClassFile)>,
    /// Enum files, by file name.
    pub enums: Vec<(String, EnumFile)>,
    /// Library files, by file name.
    pub libraries: Vec<(String, LibraryFile)>,
}

impl DataSet {
    /// The files built into the crate.
    pub fn builtin() -> Result<DataSet, CompatError> {
        let mut d = DataSet::default();
        for (name, text) in embedded::CLASSES {
            let file = format!("classes/{name}");
            d.classes
                .push((file.clone(), ClassFile::parse(&file, text)?));
        }
        for (name, text) in embedded::ENUMS {
            let file = format!("enums/{name}");
            d.enums.push((file.clone(), EnumFile::parse(&file, text)?));
        }
        for (name, text) in embedded::LIBRARIES {
            let file = format!("libraries/{name}");
            d.libraries
                .push((file.clone(), LibraryFile::parse(&file, text)?));
        }
        Ok(d)
    }
}

/// Every class of `data`, sorted by name, with each `extend` entry folded into
/// the class it extends (its members appended after the class's own).
///
/// Checks that each class is declared once and has a status, that an `extend`
/// entry names a declared class and sets only members, that member names are
/// unique within a class (properties, methods and events together), and that
/// every `partial` row has a note.
pub fn merge_classes(data: &DataSet) -> Result<Vec<ClassDoc>, CompatError> {
    let mut classes: BTreeMap<String, (String, ClassDoc)> = BTreeMap::new();
    for (file, f) in &data.classes {
        for c in f.classes.iter().filter(|c| !c.extend) {
            if let Some((other, _)) = classes.get(&c.name) {
                return Err(invalid(
                    file,
                    format!("class {} is already declared in {other}", c.name),
                ));
            }
            let Some(status) = c.status else {
                return Err(invalid(file, format!("class {} has no status", c.name)));
            };
            check_note(file, &c.name, status, &c.note)?;
            classes.insert(c.name.clone(), (file.clone(), c.clone()));
        }
    }
    for (file, f) in &data.classes {
        for e in f.classes.iter().filter(|c| c.extend) {
            if e.superclass.is_some()
                || e.creatable
                || e.service
                || !e.components.is_empty()
                || e.status.is_some()
                || !e.note.is_empty()
                || !e.doc.is_empty()
            {
                return Err(invalid(
                    file,
                    format!(
                        "extend {} may only add properties, methods and events",
                        e.name
                    ),
                ));
            }
            let Some((_, c)) = classes.get_mut(&e.name) else {
                return Err(invalid(
                    file,
                    format!("extend {} names no declared class", e.name),
                ));
            };
            c.properties.extend(e.properties.iter().cloned());
            c.methods.extend(e.methods.iter().cloned());
            c.events.extend(e.events.iter().cloned());
        }
    }
    for (file, c) in classes.values() {
        let mut seen = BTreeSet::new();
        let rows = c
            .properties
            .iter()
            .map(|p| (&p.name, p.status, &p.note))
            .chain(c.methods.iter().map(|m| (&m.name, m.status, &m.note)))
            .chain(c.events.iter().map(|e| (&e.name, e.status, &e.note)));
        for (name, status, note) in rows {
            if !seen.insert(name.as_str()) {
                return Err(invalid(
                    file,
                    format!("{}.{name} is declared twice", c.name),
                ));
            }
            check_note(file, &format!("{}.{name}", c.name), status, note)?;
        }
    }
    Ok(classes.into_values().map(|(_, c)| c).collect())
}

impl CoverageFile {
    /// The coverage table of `data`: every class (extensions folded in), enum
    /// and library, sorted by name, members sorted by name, with totals.
    pub fn from_data(data: &DataSet) -> Result<CoverageFile, CompatError> {
        let mut totals: BTreeMap<Status, usize> = BTreeMap::new();
        let mut count = |s: Status| *totals.entry(s).or_default() += 1;
        let member = |name: &str, kind: &str, status: Status, note: &str| CoverageMember {
            name: name.to_string(),
            kind: kind.to_string(),
            status,
            note: note.to_string(),
        };
        let mut classes = Vec::new();
        for c in merge_classes(data)? {
            let status = c.status.unwrap_or(Status::Missing);
            count(status);
            let mut members: Vec<CoverageMember> = c
                .properties
                .iter()
                .map(|p| member(&p.name, "property", p.status, &p.note))
                .chain(
                    c.methods
                        .iter()
                        .map(|m| member(&m.name, "method", m.status, &m.note)),
                )
                .chain(
                    c.events
                        .iter()
                        .map(|e| member(&e.name, "event", e.status, &e.note)),
                )
                .collect();
            members.sort_by(|a, b| a.name.cmp(&b.name));
            for m in &members {
                count(m.status);
            }
            classes.push(CoverageClass {
                name: c.name,
                superclass: c.superclass,
                creatable: c.creatable,
                service: c.service,
                status,
                members,
            });
        }
        let mut enums = Vec::new();
        let mut enum_names = BTreeSet::new();
        for (file, f) in &data.enums {
            for e in &f.enums {
                if !enum_names.insert(e.name.clone()) {
                    return Err(invalid(
                        file,
                        format!("enum {} is declared in two files", e.name),
                    ));
                }
                count(e.status);
                enums.push(CoverageEnum {
                    name: e.name.clone(),
                    status: e.status,
                    note: e.note.clone(),
                    items: e.items.iter().map(|i| i.name.clone()).collect(),
                });
            }
        }
        enums.sort_by(|a, b| a.name.cmp(&b.name));
        let class_names: BTreeSet<&str> = classes.iter().map(|c| c.name.as_str()).collect();
        let mut libraries = Vec::new();
        let mut lib_names = BTreeSet::new();
        for (file, f) in &data.libraries {
            for l in &f.libraries {
                if !lib_names.insert(l.name.clone()) {
                    return Err(invalid(
                        file,
                        format!("library {} is declared in two files", l.name),
                    ));
                }
                if let Some(class) = &l.class
                    && !class_names.contains(class.as_str())
                {
                    return Err(invalid(
                        file,
                        format!("{} names the unknown class {class}", l.name),
                    ));
                }
                count(l.status);
                let mut rows = |list: &[LibraryMemberDoc]| {
                    let mut out: Vec<CoverageMember> = list
                        .iter()
                        .map(|m| member(&m.name, m.kind.as_str(), m.status, &m.note))
                        .collect();
                    out.sort_by(|a, b| a.name.cmp(&b.name));
                    for m in &out {
                        count(m.status);
                    }
                    out
                };
                let members = rows(&l.members);
                let value_members = rows(&l.value_members);
                libraries.push(CoverageLibrary {
                    name: l.name.clone(),
                    class: l.class.clone(),
                    status: l.status,
                    note: l.note.clone(),
                    members,
                    value_members,
                });
            }
        }
        libraries.sort_by(|a, b| a.name.cmp(&b.name));
        Ok(CoverageFile {
            format: COVERAGE_FORMAT.to_string(),
            version: DATA_VERSION,
            totals,
            classes,
            enums,
            libraries,
        })
    }

    /// The table as committed: pretty JSON with a final newline.
    pub fn to_text(&self) -> String {
        let mut s = serde_json::to_string_pretty(self).unwrap_or_default();
        s.push('\n');
        s
    }

    /// Parses `coverage.json`.
    pub fn parse(text: &str) -> Result<CoverageFile, CompatError> {
        let f: CoverageFile = parse("coverage.json", text)?;
        check_header("coverage.json", &f.format, f.version, COVERAGE_FORMAT)?;
        Ok(f)
    }

    /// The table as the gap report keys it, each with its status:
    /// * globals by name (every library, plus `Enum`);
    /// * `Library.member` for a library's table members (a datatype's value
    ///   members are not keyed: a static scan cannot tell a value's type);
    /// * `Service.Member` for every member of a service class, inherited ones
    ///   included, and `global.Member` for an instance global such as `game`;
    /// * `Enum.<Type>` for each enum type and `Enum.<Type>.<Item>` for each item;
    /// * `Instance.new(<Class>)` for each creatable class, with the class's
    ///   status, and `GetService(<Service>)` for each service class.
    ///
    /// A key whose class or library is itself `missing` keeps its own status:
    /// rows are counted where they are declared. The synthetic `Enum` key is
    /// `partial` while any enum type is usable and `missing` otherwise.
    pub fn keys(&self) -> BTreeMap<String, Status> {
        let mut out = BTreeMap::new();
        let classes: BTreeMap<&str, &CoverageClass> =
            self.classes.iter().map(|c| (c.name.as_str(), c)).collect();
        let members_of = |class: &str| -> Vec<(&str, Status)> {
            let mut found: BTreeMap<&str, Status> = BTreeMap::new();
            let mut cur = classes.get(class).copied();
            let mut guard = 0;
            while let Some(c) = cur {
                for m in &c.members {
                    // A subclass's row wins over an inherited one of the same name.
                    found.entry(m.name.as_str()).or_insert(m.status);
                }
                cur = c
                    .superclass
                    .as_deref()
                    .and_then(|s| classes.get(s).copied());
                guard += 1;
                if guard > 64 {
                    break;
                }
            }
            found.into_iter().collect()
        };
        for c in &self.classes {
            if c.service {
                for (m, s) in members_of(&c.name) {
                    out.insert(format!("{}.{m}", c.name), s);
                }
            }
        }
        for l in &self.libraries {
            out.insert(l.name.clone(), l.status);
            for m in &l.members {
                out.insert(format!("{}.{}", l.name, m.name), m.status);
            }
            if let Some(class) = &l.class {
                for (m, s) in members_of(class) {
                    out.insert(format!("{}.{m}", l.name), s);
                }
            }
        }
        if !self.enums.is_empty() {
            let any = self.enums.iter().any(|e| e.status.is_covered());
            out.entry("Enum".to_string()).or_insert(if any {
                Status::Partial
            } else {
                Status::Missing
            });
        }
        for e in &self.enums {
            out.insert(format!("Enum.{}", e.name), e.status);
            for i in &e.items {
                out.insert(format!("Enum.{}.{i}", e.name), e.status);
            }
        }
        for c in &self.classes {
            if c.creatable {
                out.insert(format!("Instance.new({})", c.name), c.status);
            }
            if c.service {
                out.insert(format!("GetService({})", c.name), c.status);
            }
        }
        out
    }
}

