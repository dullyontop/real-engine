/// What kind of member a library member is.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "kebab-case")]
pub enum LibraryMemberKind {
    /// Called with `.` (`Vector3.new(...)`, `task.wait()`).
    #[default]
    Function,
    /// A fixed value (`Vector3.zero`).
    Constant,
    /// A value read (and maybe written) with `.`: a library field, or on a
    /// datatype's values a field such as `Magnitude`.
    Property,
    /// On a datatype's values: called with `:` (`v:Dot(w)`).
    Method,
}

impl LibraryMemberKind {
    /// `function`, `constant`, `property` or `method`.
    pub fn as_str(self) -> &'static str {
        match self {
            LibraryMemberKind::Function => "function",
            LibraryMemberKind::Constant => "constant",
            LibraryMemberKind::Property => "property",
            LibraryMemberKind::Method => "method",
        }
    }
}

fn is_function(k: &LibraryMemberKind) -> bool {
    *k == LibraryMemberKind::Function
}

