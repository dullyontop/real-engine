/// How far a class, member, enum or library is implemented.
#[derive(
    Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize, JsonSchema,
)]
#[serde(rename_all = "kebab-case")]
pub enum Status {
    /// Behaviour matches for the cases our tests cover.
    Implemented,
    /// Exists with a documented gap (see the row's `note`).
    Partial,
    /// Raises `RE9001` or `RE9002` with the member's name.
    StubError,
    /// Declared, not built yet.
    Missing,
}

impl Status {
    /// `"implemented"`, `"partial"`, `"stub-error"` or `"missing"`.
    pub fn as_str(self) -> &'static str {
        match self {
            Status::Implemented => "implemented",
            Status::Partial => "partial",
            Status::StubError => "stub-error",
            Status::Missing => "missing",
        }
    }

    /// True unless the status is `missing`: a script that uses the member gets
    /// either the behaviour or a clear error.
    pub fn is_covered(self) -> bool {
        self != Status::Missing
    }
}

fn is_false(b: &bool) -> bool {
    !*b
}

