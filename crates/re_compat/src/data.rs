//! The data formats of the compatibility layer (ADR-0034): class files
//! (`classes/*.json`), enum files (`enums/*.json`), library files
//! (`libraries/*.json`) and the generated coverage table (`coverage.json`).
//!
//! Names, signatures and default values in these files are facts about an
//! API. Every `doc` string is written for this repository; no vendor prose is
//! copied.
//!
//! Each file names its format and version. The JSON Schemas of all four
//! formats come from [`schemas`] and are written to `schemas/` by
//! `cargo xtask schemas`.
//!
//! # Member status
//!
//! Every class, member, enum and library row has a [`Status`]:
//! * `implemented`: the behaviour matches for the cases our tests cover;
//! * `partial`: it exists with a documented gap, written in the row's `note`
//!   (a `partial` row without a note is refused);
//! * `stub-error`: calling it raises `RE9001` or `RE9002` with its name;
//! * `missing`: declared, not built yet. The gap report counts it as missing.

