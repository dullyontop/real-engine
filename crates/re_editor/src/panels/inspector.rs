//! The inspector: the active entity's components and their fields, with
//! controls to add and remove components. With several entities selected it
//! says how many above the active one, which is the one it edits.

use std::collections::BTreeSet;

use egui::RichText;
use re_scene::{Generated, World};
use serde_json::json;

use crate::editor::{Action, Editor, Pending, command, note_key};
use crate::widgets::{self, Fields};

pub(super) fn inspector(
    ed: &mut Editor,
    ui: &mut egui::Ui,
    world: &World,
    actions: &mut Vec<Action>,
) {
    ui.heading("Inspector");
    let Some(id) = ed.selection.active().map(str::to_string) else {
        ui.label(RichText::new("Select an entity in the hierarchy.").weak());
        return;
    };
    let count = ed.selection.len();
    if count > 1 {
        ui.label(RichText::new(format!("{count} selected; showing the active one")).weak())
            .on_hover_text("The last one selected. Editing several at once is not supported yet.");
    }
    let Ok(e) = world.entity(&id) else {
        ui.label(RichText::new(format!("{id} no longer exists.")).weak());
        return;
    };
    let name = world.name_of(e);
    ui.label(RichText::new(if name.is_empty() { &id } else { name }).strong());
    ui.label(RichText::new(&id).monospace().weak());
    if let Some(g) = world.ecs.get::<Generated>(e) {
        let source = world.id_of(g.source).unwrap_or("?");
        ui.label(
            RichText::new(format!(
                "Generated by {source} (key {}): edits are kept as overrides.",
                g.key
            ))
            .weak(),
        );
    } else if let Some(note) = note_field(ui, &mut ed.pending, &id, world.note_of(e)) {
        actions.push(command(
            "scene.apply",
            json!({
                "label": format!("note on {id}"),
                "ops": [{ "op": "set_note", "id": id, "note": note }],
            }),
        ));
    }
    let registry = &world.registry;
    let present = registry.components_of(&world.ecs, e);
    let mut fields = Fields::new(ed, world);
    for key in &present {
        let schema = registry.schema(*key);
        let values = registry.get_all(&world.ecs, e, *key).unwrap_or_default();
        egui::CollapsingHeader::new(RichText::new(&schema.name).strong())
            .id_salt(("re_editor.component", &id, &schema.name))
            .default_open(true)
            .show(ui, |ui| {
                if !schema.doc.is_empty() {
                    ui.label(RichText::new(&schema.doc).weak().small());
                }
                egui::Grid::new(("re_editor.fields", &id, &schema.name))
                    .num_columns(2)
                    .striped(true)
                    .show(ui, |ui| {
                        for (index, value) in values.iter().enumerate() {
                            widgets::field_row(ui, &mut fields, &id, *key, index, value, actions);
                        }
                    });
                if ui.small_button("Remove component").clicked() {
                    actions.push(command(
                        "component.remove",
                        json!({ "id": id, "component": schema.name }),
                    ));
                }
            });
    }
    let have: BTreeSet<&str> = present
        .iter()
        .map(|k| registry.schema(*k).name.as_str())
        .collect();
    let mut missing: Vec<&str> = registry
        .schemas()
        .map(|s| s.name.as_str())
        .filter(|n| !have.contains(n))
        .collect();
    missing.sort_unstable();
    ui.separator();
    egui::ComboBox::from_id_salt(("re_editor.add_component", &id))
        .selected_text("Add component…")
        .show_ui(ui, |ui| {
            for name in missing {
                if ui.selectable_label(false, name).clicked() {
                    actions.push(command(
                        "component.add",
                        json!({ "id": id, "component": name }),
                    ));
                }
            }
        });
}

/// The note kept with an authored entity in the scene file: a text field
/// that returns its text when it loses focus changed (Escape drops the
/// edit). A generated entity keeps no note, so it has no field.
fn note_field(ui: &mut egui::Ui, pending: &mut Pending, id: &str, current: &str) -> Option<String> {
    let key = note_key(id);
    let mut text = pending
        .texts
        .get(&key)
        .cloned()
        .unwrap_or_else(|| current.to_string());
    let r = ui
        .add(
            egui::TextEdit::multiline(&mut text)
                .hint_text("Note")
                .desired_rows(1)
                .desired_width(f32::INFINITY),
        )
        .on_hover_text("Kept with the entity in the scene file; saved when the field loses focus");
    pending.widgets(&key, std::slice::from_ref(&r));
    if r.lost_focus() {
        pending.texts.remove(&key);
        let cancelled = ui.input(|i| i.key_pressed(egui::Key::Escape));
        return (!cancelled && text != current).then_some(text);
    }
    if r.has_focus() {
        pending.texts.insert(key, text);
    } else {
        pending.texts.remove(&key);
    }
    None
}
